    print("\n=== SIMULASI 3: Pencarian Case-Sensitive Gagal (Bug 3) ===")
    app.tambah_kontak("Siti Aminah", "08555555555")
    app.cari_kontak("siti")  # "Kontak tidak ditemukan" karena 's' huruf kecil